import { afterEach, expect, test, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { SeasonPanel } from './SeasonPanel.jsx';
import { ScopeSaveActions } from './ScopeSaveActions.jsx';
import fixture from '../../fixtures/catalog.v1.json';
const race = fixture.races.find(value => value.id === 'race-road-split');
const entries = race.entry_scopes.map((scope, index) => ({ id: 'saved-' + index, scope_id: scope.id, status: index ? 'registered' : 'planned', created_at: '2026-11-14T00:00:00Z', scope, race: { ...race, entry_scopes: undefined } }));
const state = { status: 'member', account: { id: 'alice', email: 'alice@example.test' }, contextEpoch: 7, entries: { status: 'ready', items: entries }, busy: false, revalidating: false };
const client = () => ({ loadEntries: vi.fn(), saveScope: vi.fn(), removeEntry: vi.fn() });
afterEach(cleanup);
test('season has both scopes outside public selection and detail cannot invent sibling scope', () => {
  const controller = client();
  const { rerender } = render(<SeasonPanel account={state} controller={controller} />);
  expect(screen.getByText(/sans les filtres/)).toBeTruthy();
  const rows = screen.getAllByRole('button', { name: /Course fictive/ });
  expect(rows).toHaveLength(2); fireEvent.click(rows[0]);
  expect(screen.getByText(entries[0].scope.raw_label)).toBeTruthy();
  expect(screen.queryByText(entries[1].scope.raw_label)).toBeNull();
  expect(screen.getByText(/votre déclaration, non vérifiée/)).toBeTruthy();
  rerender(<SeasonPanel account={{ ...state, contextEpoch: 8, account: { id: 'bob' }, entries: { status: 'ready', items: [] } }} controller={controller} />);
  expect(screen.queryByText(race.name)).toBeNull();
  expect(screen.getByText(/Votre saison est vide/)).toBeTruthy();
});
test('scope controls use exact scope IDs and server saved IDs, no autosave on login', () => {
  const controller = client(), onConnect = vi.fn();
  const { rerender } = render(<ScopeSaveActions scopeId="other opaque scope" account={{ ...state, status: 'anonymous', account: null }} controller={controller} onConnect={onConnect} />);
  fireEvent.click(screen.getByRole('button')); expect(onConnect).toHaveBeenCalledOnce();
  expect(controller.saveScope).not.toHaveBeenCalled();
  rerender(<ScopeSaveActions scopeId="other opaque scope" account={state} controller={controller} onConnect={onConnect} />);
  fireEvent.change(screen.getByLabelText('Votre statut pour cette liste'), { target: { value: 'completed' } });
  expect(controller.saveScope).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Sauvegarder cette liste' }));
  expect(controller.saveScope).toHaveBeenCalledWith('other opaque scope', 'completed');
  rerender(<ScopeSaveActions scopeId={entries[0].scope_id} account={state} controller={controller} onConnect={onConnect} />);
  fireEvent.change(screen.getByLabelText('Votre statut pour cette liste'), { target: { value: 'registered' } });
  expect(controller.saveScope).toHaveBeenCalledWith(entries[0].scope_id, 'registered');
  fireEvent.click(screen.getByRole('button', { name: 'Retirer cette sauvegarde' }));
  expect(controller.removeEntry).toHaveBeenCalledWith(entries[0].id);
});
test('loading/error never shows old private scopes, retry is read only', () => {
  const controller = client();
  const { rerender } = render(<SeasonPanel account={{ ...state, revalidating: true }} controller={controller} />);
  expect(screen.queryByText(race.name)).toBeNull();
  rerender(<SeasonPanel account={{ ...state, entries: { status: 'error', items: [], error: { code: 'network' } } }} controller={controller} />);
  fireEvent.click(screen.getByRole('button', { name: 'Actualiser ma saison' }));
  expect(controller.loadEntries).toHaveBeenCalledOnce();
  expect(controller.saveScope).not.toHaveBeenCalled();
  expect(within(screen.getByRole('alert')).getByText(/peut avoir déjà/)).toBeTruthy();
});
